// Package winname holds the Windows API names the offensive modules reference,
// stored masked (internal/obfuscate) and decoded once at init, so they do not
// appear as plaintext in the compiled binary.
//
// Two things leak a name into a static binary: the string literal itself, and
// the SYMBOL NAME of any package-level variable. So the identifiers below are
// deliberately abbreviated — none contains its API name as a substring — and
// the real name is documented only in a comment (comments do not compile in).
// `winname.NtAllocateVirtualMemory` would have re-introduced exactly the string
// the mask removed.
//
// Why this exists: a `strings`/YARA sweep for "MiniDumpWriteDump",
// "AmsiScanBuffer" or the ntdll syscall names is a cheap way to fingerprint
// credential-dumping / AMSI-bypass tooling. Keeping them masked raises the cost
// of such a rule. It is NOT encryption — the mask key ships in the binary — and
// it is NOT anonymity: the module path `github.com/DevCop95/obliteratus/...`
// is in every symbol, so a rule that targets this tool by name still hits.
// Build releases with `-ldflags="-s -w"` to strip the symbol table as well.
//
// Honest residual: golang.org/x/sys/windows declares its own
// `Kernel32 = NewLazySystemDLL("kernel32.dll")` / `NTDLL = ...("ntdll.dll")`
// and its zsyscall/syscall tables embed the strings "VirtualProtect",
// "ReadProcessMemory", "WriteProcessMemory", "OpenProcess" and "CloseHandle".
// All of those survive in any Go binary that links the package, so masking them
// here is redundant — the value of this package is the high-signal set above.
//
// names_test.go pins every value, so a corrupted literal fails the build.
